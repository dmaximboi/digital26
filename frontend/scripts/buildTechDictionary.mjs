const seen = new Set();
const entries = [];
for (const [term, aka, category, core] of CORE) {
  const key = `${term.toLowerCase()}|${category}`;
  if (seen.has(key)) continue;
  seen.add(key);
  const aliases = aka ? [aka] : [];
  entries.push({
    id: `${category}-${term.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "") || "term"}-${entries.length}`,
    term,
    aka: aliases,
    category,
    definition: expand(term, aka, category, core),
  });
}

entries.sort((a, b) => a.term.localeCompare(b.term, "en", { sensitivity: "base" }));

const out = join(root, "src/data/techDictionary.json");
writeFileSync(out, `${JSON.stringify({ generatedAt: new Date().toISOString(), count: entries.length, entries }, null, 0)}\n`);
console.log(`wrote ${entries.length} terms to ${out}`);
writePublicGlossary(entries);
